        <section id="faq" class="section" aria-labelledby="faq-title">
            <div class="container">
                <div class="section-head">
                    <h2 id="faq-title">Najczęściej zadawane pytania</h2>
                </div>
                <div class="faq">
                    <details>
                        <summary>Co to jest RRSO?</summary>
                        <div class="faq-answer">
                            <p>
                                RRSO, czyli rzeczywista roczna stopa oprocentowania, pokazuje całkowity koszt kredytu ponoszony przez
                                konsumenta jako procent kwoty kredytu w skali roku. Uwzględnia odsetki, prowizje, opłaty i inne koszty,
                                a także terminy wypłat i spłat, dzięki czemu pozwala porównywać oferty o różnej długości i strukturze kosztów.
                            </p>
                        </div>
                    </details>
                    <details>
                        <summary>Jak obliczyć RRSO?</summary>
                        <div class="faq-answer">
                            <p>
                                RRSO to stopa X, przy której suma zdyskontowanych wypłat kredytu jest równa sumie zdyskontowanych spłat
                                i opłat: ΣC<sub>k</sub>(1+X)<sup>−t<sub>k</sub></sup> = ΣD<sub>l</sub>(1+X)<sup>−s<sub>l</sub></sup>.
                                Czas liczy się w latach od dnia pierwszej wypłaty. Równanie rozwiązuje się numerycznie – w kalkulatorze
                                wystarczy wpisać daty i kwoty.
                            </p>
                        </div>
                    </details>
                    <details>
                        <summary>Ile wynoszą odsetki maksymalne w 2026 roku?</summary>
                        <div class="faq-answer">
                            <p>
                                Od <span data-legal="referenceRateSince">5 marca 2026 r.</span>, przy stopie referencyjnej NBP
                                <span data-legal="referenceRate">3,75%</span>, odsetki maksymalne wynoszą
                                <span data-legal="maxInterest">14,50%</span> w skali roku, czyli dwukrotność sumy stopy referencyjnej
                                i <span data-legal="maxInterestMargin">3,5</span> punktu procentowego (art. 359 § 2¹ Kodeksu cywilnego).
                                Maksymalne odsetki za opóźnienie wynoszą <span data-legal="maxLateInterest">18,50%</span> rocznie
                                (art. 481 § 2¹ Kodeksu cywilnego).
                            </p>
                        </div>
                    </details>
                    <details>
                        <summary>Jak obliczyć maksymalne pozaodsetkowe koszty kredytu (MPKK)?</summary>
                        <div class="faq-answer">
                            <p>
                                Zgodnie z art. 36a ustawy o kredycie konsumenckim MPKK = K × <span data-legal="mpkkFixed">10%</span>
                                + K × n/R × <span data-legal="mpkkAnnual">10%</span>, gdzie K to całkowita kwota kredytu, n – okres
                                spłaty w dniach, a R – liczba dni w roku. Koszty pozaodsetkowe nie mogą przekroczyć
                                <span data-legal="mpkkCap">45%</span> K. Dla kredytu na okres krótszy niż
                                <span data-legal="mpkkShortDays">30</span> dni limit wynosi <span data-legal="mpkkShortPct">5%</span> K.
                            </p>
                        </div>
                    </details>
                    <details>
                        <summary>Czy limity są takie same dla banków i firm pożyczkowych?</summary>
                        <div class="faq-answer">
                            <p>
                                Tak. Odsetki maksymalne i limit MPKK obowiązują każdego kredytodawcę udzielającego kredytu
                                konsumenckiego – zarówno banki, jak i instytucje pożyczkowe. W kalkulatorze można jednak ustawić osobne
                                wartości dla każdego typu kredytodawcy.
                            </p>
                        </div>
                    </details>
                    <details>
                        <summary>Dlaczego RRSO chwilówki może wynosić kilkaset procent?</summary>
                        <div class="faq-answer">
                            <p>
                                RRSO przelicza koszt na skalę roczną z uwzględnieniem procentu składanego. Koszt 10% za 30 dni daje
                                RRSO około 218,87%, bo taki koszt powtórzyłby się ponad 12 razy w roku. Wysokie RRSO krótkiej pożyczki
                                nie musi więc oznaczać przekroczenia limitów prawnych.
                            </p>
                        </div>
                    </details>
                    <details>
                        <summary>Czy kalkulator zapisuje wprowadzone dane?</summary>

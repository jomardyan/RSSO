                        <dt>l</dt><dd>numer kolejny spłaty lub wniesionej opłaty</dd>
                        <dt>D<sub>l</sub></dt><dd>kwota spłaty lub opłaty (w kalkulatorze: kwota ujemna)</dd>
                        <dt>s<sub>l</sub></dt><dd>okres w latach lub ułamkach lat od dnia pierwszej wypłaty do dnia spłaty lub opłaty l</dd>
